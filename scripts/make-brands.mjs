#!/usr/bin/env node
// Builds apps/launcher/js/core/brands.js – sharp vector logos for inputs (HDMI devices) where the
// TV's own icons are weak. Source: simple-icons (CC0) + a few hand-drawn ones.   node scripts/make-brands.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { APPS } from './lib.mjs';

const require = createRequire(import.meta.url);
const si = require('simple-icons');

// key: [simple-icons name | null, title, background (gradient), foreground, match]
const BRANDS = [
  ['playstation', 'siPlaystation', 'PlayStation', 'linear-gradient(150deg,#0a5bd6 0%,#003791 100%)', '#fff', 'playstation|\\bps ?[2345]\\b|ps5|ps4'],
  ['nvidia', 'siNvidia', 'NVIDIA SHIELD', 'linear-gradient(150deg,#1d1f1c 0%,#0b0c0a 100%)', '#76B900', 'shield|nvidia'],
  ['xbox', null, 'Xbox', 'linear-gradient(150deg,#1c9a1c 0%,#0e6a0e 100%)', '#fff', 'xbox'],
  ['switch', null, 'Nintendo Switch', 'linear-gradient(150deg,#ff2d3a 0%,#c4000f 100%)', '#fff', 'nintendo|switch'],
  ['appletv', 'siAppletv', 'Apple TV', 'linear-gradient(150deg,#2a2a2d 0%,#0c0c0d 100%)', '#fff', 'apple ?tv'],
  ['googletv', 'siGoogletv', 'Google TV', 'linear-gradient(150deg,#2a2d33 0%,#121417 100%)', '#fff', 'chromecast|google ?tv'],
  ['roku', 'siRoku', 'Roku', 'linear-gradient(150deg,#7a3aa8 0%,#4b1c6e 100%)', '#fff', 'roku'],
  ['steam', 'siSteam', 'Steam', 'linear-gradient(150deg,#1b2838 0%,#0e141c 100%)', '#fff', 'steam'],
  ['kodi', 'siKodi', 'Kodi', 'linear-gradient(150deg,#1d2a35 0%,#0f171e 100%)', '#17B2E7', 'kodi']
];

// Hand-drawn (24×24, filled with evenodd).
const CUSTOM = {
  xbox: 'M12 1.6a10.4 10.4 0 1 0 0 20.8 10.4 10.4 0 0 0 0-20.8Zm-4.9 3.2C8.6 3.6 10.2 3 12 3s3.4.6 4.9 1.8c-1.6-.4-3.2.4-4.9 1.8-1.7-1.4-3.3-2.2-4.9-1.8Zm-1.9 2.1c1.5-.3 3.6 1.2 5.5 3.2-2.6 2.9-4.6 6-4.9 8.2A8.9 8.9 0 0 1 3.1 12c0-1.9.8-3.7 2.1-5.1Zm13.6 0A8.9 8.9 0 0 1 20.9 12c0 2.6-1.1 4.9-2.8 6.5-.3-2.2-2.3-5.3-4.9-8.2 1.9-2 4-3.5 5.6-3.4ZM12 11.4c2.6 2.8 4.7 6 4.9 8.1A8.9 8.9 0 0 1 12 21a8.9 8.9 0 0 1-4.9-1.5c.2-2.1 2.3-5.3 4.9-8.1Z',
  switch: 'M9.5 2.5H7A4.5 4.5 0 0 0 2.5 7v10A4.5 4.5 0 0 0 7 21.5h2.5Zm-3 3.6a1.9 1.9 0 1 1 0 3.8 1.9 1.9 0 0 1 0-3.8ZM14.5 2.5V21.5H17a4.5 4.5 0 0 0 4.5-4.5V7A4.5 4.5 0 0 0 17 2.5Zm1.4 1.5H17a3 3 0 0 1 3 3v10a3 3 0 0 1-3 3h-1.1Zm1.6 9.6a1.9 1.9 0 1 1 0 3.8 1.9 1.9 0 0 1 0-3.8Z'
};

const out = {};
for (const [key, siName, title, bg, fg, match] of BRANDS) {
  const path = siName ? si[siName] && si[siName].path : CUSTOM[key];
  if (!path) { console.warn('missing:', key); continue; }
  out[key] = { title, bg, fg, match, path };
}

const js = `/* GENERATED by scripts/make-brands.mjs – edit there. Logos: simple-icons (CC0) + hand-drawn. */
(function (global) {
  'use strict';
  const BRANDS = ${JSON.stringify(out, null, 2)};
  const order = Object.keys(BRANDS);
  global.Brands = {
    // Find a brand from free text (e.g. the HDMI device's name).
    match(text) {
      const t = String(text || '').toLowerCase();
      for (const k of order) if (new RegExp(BRANDS[k].match, 'i').test(t)) return Object.assign({ key: k }, BRANDS[k]);
      return null;
    },
    get: (k) => (BRANDS[k] ? Object.assign({ key: k }, BRANDS[k]) : null),
    svg: (b) => '<svg class="brand-mark" viewBox="0 0 24 24" aria-hidden="true"><path fill="currentColor" fill-rule="evenodd" d="' + b.path + '"/></svg>'
  };
})(window);
`;
writeFileSync(join(APPS, 'launcher', 'js', 'core', 'brands.js'), js);
console.log('✓ js/core/brands.js:', Object.keys(out).join(', '));
